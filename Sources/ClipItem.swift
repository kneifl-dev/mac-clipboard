import AppKit
import SwiftUI

/// Typ obsahu ve schránce.
enum ClipKind {
    case text, link, richText, image, file, color, other

    var label: String {
        switch self {
        case .text: return "Text"
        case .link: return "Odkaz"
        case .richText: return "Formátovaný text"
        case .image: return "Obrázek"
        case .file: return "Soubor"
        case .color: return "Barva"
        case .other: return "Jiné"
        }
    }

    var symbol: String {
        switch self {
        case .text: return "text.alignleft"
        case .link: return "link"
        case .richText: return "textformat"
        case .image: return "photo"
        case .file: return "doc"
        case .color: return "paintpalette"
        case .other: return "questionmark.square.dashed"
        }
    }

    var tint: Color {
        switch self {
        case .text: return .gray
        case .link: return .blue
        case .richText: return .purple
        case .image: return .green
        case .file: return .orange
        case .color: return .pink
        case .other: return .secondary
        }
    }
}

/// Jedna zkopírovaná položka. Drží kopii všech reprezentací ze schránky
/// pouze v paměti – nic se nezapisuje na disk.
final class ClipItem: Identifiable {
    let id = UUID()
    let date = Date()
    let kind: ClipKind
    let preview: String
    let detail: String
    let thumbnail: NSImage?
    let sourceApp: String?
    let signature: Int
    private let representations: [[NSPasteboard.PasteboardType: Data]]

    private init(kind: ClipKind, preview: String, detail: String, thumbnail: NSImage?,
                 sourceApp: String?, representations: [[NSPasteboard.PasteboardType: Data]]) {
        self.kind = kind
        self.preview = preview
        self.detail = detail
        self.thumbnail = thumbnail
        self.sourceApp = sourceApp
        self.representations = representations

        var hasher = Hasher()
        for item in representations {
            for type in item.keys.sorted(by: { $0.rawValue < $1.rawValue }) {
                hasher.combine(type.rawValue)
                hasher.combine(item[type])
            }
        }
        self.signature = hasher.finalize()
    }

    /// Typy, které password managery a systém označují jako citlivé / dočasné – ty neukládáme.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    /// Maximální velikost jedné položky v paměti (větší se přeskočí).
    private static let maxBytes = 64 * 1024 * 1024

    static func capture(from pb: NSPasteboard, sourceApp: String?) -> ClipItem? {
        guard let items = pb.pasteboardItems, !items.isEmpty else { return nil }
        let allTypes = Set(items.flatMap { $0.types })
        if !allTypes.isDisjoint(with: ignoredTypes) { return nil }

        var reps: [[NSPasteboard.PasteboardType: Data]] = []
        var total = 0
        for item in items {
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    dict[type] = data
                    total += data.count
                }
            }
            if !dict.isEmpty { reps.append(dict) }
        }
        guard total > 0, total <= maxBytes else { return nil }

        let string = pb.string(forType: .string)
        let hasImage = allTypes.contains(.png) || allTypes.contains(.tiff)

        // Soubory z Finderu
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let names = urls.map { $0.lastPathComponent }.joined(separator: ", ")
            let detail = urls.count == 1 ? urls[0].deletingLastPathComponent().path
                                         : "\(urls.count) \(urls.count < 5 ? "soubory" : "souborů")"
            let icon = NSWorkspace.shared.icon(forFile: urls[0].path)
            return ClipItem(kind: .file, preview: names, detail: detail, thumbnail: icon,
                            sourceApp: sourceApp, representations: reps)
        }

        // Obrázek (bez textové podoby – jinak jde o např. buňky z tabulky)
        if hasImage, string == nil, let image = NSImage(pasteboard: pb) {
            let px = image.representations.first.map { "\($0.pixelsWide) × \($0.pixelsHigh) px" }
                ?? "\(Int(image.size.width)) × \(Int(image.size.height))"
            return ClipItem(kind: .image, preview: "Obrázek", detail: "\(px) · \(byteString(total))",
                            thumbnail: image, sourceApp: sourceApp, representations: reps)
        }

        // Barva (např. z výběru barev)
        if string == nil, allTypes.contains(.color),
           let color = NSColor(from: pb)?.usingColorSpace(.sRGB) {
            let hex = String(format: "#%02X%02X%02X",
                             Int(color.redComponent * 255), Int(color.greenComponent * 255), Int(color.blueComponent * 255))
            return ClipItem(kind: .color, preview: hex, detail: "sRGB", thumbnail: swatch(color),
                            sourceApp: sourceApp, representations: reps)
        }

        if let string, !string.isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let lines = string.split(separator: "\n", omittingEmptySubsequences: false).count
            var detail = "\(string.count) znaků"
            if lines > 1 { detail += " · \(lines) řádků" }

            let kind: ClipKind
            if isLink(trimmed) {
                kind = .link
                detail = URL(string: trimmed)?.host ?? detail
            } else if allTypes.contains(.rtf) || allTypes.contains(.html) || allTypes.contains(.rtfd) {
                kind = .richText
            } else {
                kind = .text
            }
            return ClipItem(kind: kind, preview: oneLine(trimmed.isEmpty ? string : trimmed), detail: detail,
                            thumbnail: nil, sourceApp: sourceApp, representations: reps)
        }

        let typeName = items.first?.types.first?.rawValue ?? "neznámý typ"
        return ClipItem(kind: .other, preview: typeName, detail: byteString(total),
                        thumbnail: nil, sourceApp: sourceApp, representations: reps)
    }

    /// Vrátí položku zpět do systémové schránky se všemi původními formáty.
    func write(to pb: NSPasteboard) {
        pb.clearContents()
        let items = representations.map { dict -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            return item
        }
        pb.writeObjects(items)
    }

    // MARK: - Pomocné funkce

    private static func isLink(_ s: String) -> Bool {
        guard !s.contains(where: { $0.isWhitespace }), let url = URL(string: s),
              let scheme = url.scheme?.lowercased() else { return false }
        return ["http", "https", "mailto", "ftp"].contains(scheme) && (url.host != nil || scheme == "mailto")
    }

    private static func oneLine(_ s: String) -> String {
        let collapsed = s.prefix(400).split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
        return collapsed.isEmpty ? "(mezery)" : collapsed
    }

    private static func byteString(_ bytes: Int) -> String {
        ByteCountFormatter.string(fromByteCount: Int64(bytes), countStyle: .memory)
    }

    private static func swatch(_ color: NSColor) -> NSImage {
        NSImage(size: NSSize(width: 36, height: 36), flipped: false) { rect in
            color.setFill()
            rect.fill()
            return true
        }
    }
}
